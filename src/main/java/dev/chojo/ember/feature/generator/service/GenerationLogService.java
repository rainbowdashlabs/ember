package dev.chojo.ember.feature.generator.service;

import dev.chojo.ember.feature.generator.entity.GenerationLogEntry;
import dev.chojo.ember.feature.generator.repository.DocumentGenerationRepository;
import dev.chojo.ember.feature.members.service.MemberNameResolver;
import jakarta.inject.Inject;
import jakarta.inject.Singleton;
import org.jspecify.annotations.Nullable;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * The documents a station generated from templates, as a list: who has which document, from which
 * template and which version of it, generated by whom and when, and who issued it.
 */
@Singleton
public class GenerationLogService {
    /** How many entries a page holds where the reader asks for no number. */
    public static final int DEFAULT_LIMIT = 500;

    /** The most entries one page holds. */
    public static final int MAX_LIMIT = 1000;

    private final DocumentGenerationRepository generations;
    private final MemberNameResolver names;

    @Inject
    public GenerationLogService(DocumentGenerationRepository generations, MemberNameResolver names) {
        this.generations = generations;
        this.names = names;
    }

    /**
     * One generated document as the list shows it.
     *
     * @param id              the entry of the generation log
     * @param generatedAt     when it was generated
     * @param templateId      the template it came from
     * @param templateName    what the template is called now
     * @param templateVersion the version of the template at the time
     * @param ofAssociation   whether the template is one of the station's association
     * @param memberId        the member it is about, or null once they were deleted
     * @param memberName      the member's name, or null once they were deleted
     * @param generatedByName who generated it, or null once they are gone
     * @param selfService     whether it was generated through self service
     * @param documentId      the member document it was filed as, or null once that was deleted
     * @param issuerName      who issued it, or null where it names nobody or they are gone
     * @param issuerFunction  what the issuer does at the station, as printed, or null
     */
    public record GeneratedDocumentEntry(
            int id,
            Instant generatedAt,
            int templateId,
            String templateName,
            int templateVersion,
            boolean ofAssociation,
            @Nullable Integer memberId,
            @Nullable String memberName,
            @Nullable String generatedByName,
            boolean selfService,
            @Nullable Integer documentId,
            @Nullable String issuerName,
            @Nullable String issuerFunction) {}

    /**
     * One page of the documents generated at a station. The names of everybody the page names are read
     * together rather than row by row.
     *
     * @param stationId the station
     * @param limit     how many entries at most, held between 1 and {@value #MAX_LIMIT}
     * @param offset    how many of the newest entries to pass over, none where it is below zero
     * @return the documents generated at the station, the newest first
     */
    public List<GeneratedDocumentEntry> list(int stationId, int limit, int offset) {
        var entries = generations.forStation(stationId, Math.clamp(limit, 1, MAX_LIMIT), Math.max(offset, 0));
        var named = names.identified(entries.stream()
                .flatMap(entry -> Stream.of(entry.memberId(), entry.generatedBy(), entry.issuerId()))
                .filter(Objects::nonNull)
                .collect(Collectors.toSet()));
        return entries.stream().map(entry -> entry(entry, named)).toList();
    }

    private static GeneratedDocumentEntry entry(GenerationLogEntry entry, Map<Integer, String> named) {
        return new GeneratedDocumentEntry(
                entry.id(),
                entry.generatedAt(),
                entry.templateId(),
                entry.templateName(),
                entry.templateVersion(),
                entry.ofAssociation(),
                entry.memberId(),
                nameOf(entry.memberId(), named),
                nameOf(entry.generatedBy(), named),
                entry.selfService(),
                entry.documentId(),
                nameOf(entry.issuerId(), named),
                entry.issuerFunction());
    }

    private static @Nullable String nameOf(@Nullable Integer memberId, Map<Integer, String> named) {
        return memberId == null ? null : named.get(memberId);
    }
}
