#!/usr/bin/env node
/**
 * Writes the help centre's search index from the pages tree.
 *
 * The list this replaces was kept by hand, and a page added without an entry was simply unsearchable
 * until somebody noticed: that is how the search came to answer nothing on 258 of its 259 pages. Reading
 * the pages instead makes an unsearchable page impossible rather than merely detectable.
 *
 * Run it with `./toolchain.sh fe-help-index`. The linter of the same name checks that what is committed
 * is what this writes, so the two cannot drift.
 */

import {writeFileSync} from 'fs'
import {join} from 'path'
import {collectHelpPages} from './help-index.mjs'
import {SRC, GREEN, RESET} from './lint-utils.mjs'

export const TARGET = join(SRC, 'composables', 'helpPages.generated.ts')

/**
 * The file as it should stand for the pages that exist now.
 */
export function renderHelpPages() {
    const rows = collectHelpPages().map(page => {
        const prefixes = page.prefixes.map(prefix => `'${prefix}'`).join(', ')
        const drawn = page.prefixes.length === 1 ? prefixes : `[${prefixes}]`
        return `    {route: '${page.route}', path: '${page.path}', i18nPrefix: ${drawn}},`
    })
    return `/*
 *     SPDX-License-Identifier: AGPL-3.0-only
 *
 *     Copyright (C) RainbowDashLabs and Contributor
 */
/**
 * Generated by \`./toolchain.sh fe-help-index\` from the pages under \`src/pages/helpcenter\` and the
 * articles they mount. Do not edit: a page is in the search because it exists, and the way to change
 * what is in here is to change the page or the keys its article draws from.
 */
import type {HelpPage} from './useHelpSearch'

export const HELP_PAGES: HelpPage[] = [
${rows.join('\n')}
]
`
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
    writeFileSync(TARGET, renderHelpPages())
    console.log(`${GREEN}Wrote${RESET} ${TARGET.replace(SRC, 'src')} (${collectHelpPages().length} pages)`)
}
